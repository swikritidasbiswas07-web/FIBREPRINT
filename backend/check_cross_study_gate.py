"""FIBREPRINT v0.24: fail-closed cross-study validation readiness gate.

Only standard-library modules. Does not download datasets, fit models or create
synthetic measurement rows. An eligible external CSV is NOT proof of comparable
protocols. Zero external metrics are generated by this script.
"""
import argparse
import csv
import hashlib
import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

COLUMNS = ["study_id", "source_doi", "source_locator", "record_type", "fabric_id", "wash_id",
           "release_value", "release_unit", "measurement_basis", "collection_method",
           "wash_protocol", "fabric_composition", "fabric_construction", "gsm", "notes"]


def gate(protocols, candidate, external_csv=None):
    src = protocols["sources"]
    train = src["vassilenko_2021"]
    if candidate not in src or candidate == "vassilenko_2021":
        raise ValueError("Candidate must be an external study registered in cross_study_protocols.json")
    ext = src[candidate]
    blockers = []
    warnings = []
    checks = {}
    def check(name, passed, reason):
        checks[name] = {"pass": bool(passed), "detail": reason}
        if not passed:
            blockers.append(reason)
    check("same_unit", ext.get("unit") == train["unit"],
          "Target units are not both documented as mg/kg")
    check("same_measurement_basis", ext.get("measurement_basis") == train["measurement_basis"],
          "Study outcome denominators are not comparable at the individual-fabric wash level")
    check("same_specimen_unit", ext.get("specimen_unit") == train["specimen_unit"],
          "External outcome is not an individual-fabric specimen measurement")
    check("same_laundry_device", ext.get("laundry_device") == train["laundry_device"],
          "Different laundering apparatus: a protocol/domain shift must be reviewed")
    check("protocol_harmonised", ext.get("protocol_compatibility") == "verified_compatible",
          "Protocol equivalence has not been established or independently reviewed")
    check("raw_measurements_verified", ext.get("raw_measurements_verified_accessible") is True,
          "Individual external measurements have not been verified accessible")
    # Published means are never taken to represent independent replicates.
    aggregate_count = sum(x["source_id"] == candidate for x in protocols.get("published_aggregates_not_training_rows", []))
    if aggregate_count:
        warnings.append(f"{aggregate_count} published summary values exist; these are NOT individual measurements")
    rows = 0
    distinct_fabrics = set()
    reasons = Counter()
    sha256 = None
    if external_csv is None:
        blockers.append("No independently transcribed and source-verified external measurement CSV provided")
    else:
        raw = external_csv.read_bytes()
        sha256 = hashlib.sha256(raw).hexdigest()
        with external_csv.open("r", encoding="utf-8-sig", newline="") as fh:
            reader = csv.DictReader(fh)
            absent = sorted(set(COLUMNS) - set(reader.fieldnames or []))
            if absent:
                blockers.append("Missing CSV columns: " + ", ".join(absent))
            else:
                seen = set()
                for row in reader:
                    rows += 1
                    if row["study_id"].strip() != candidate: reasons["wrong_study_id"] += 1
                    if row["record_type"].strip() != "individual_measurement": reasons["not_individual_measurement"] += 1
                    if row["release_unit"].strip().lower() != "mg/kg": reasons["not_mg_per_kg"] += 1
                    if not row["source_locator"].strip(): reasons["missing_source_locator"] += 1
                    if not row["fabric_id"].strip() or not row["wash_id"].strip(): reasons["missing_fabric_or_wash_id"] += 1
                    if not row["collection_method"].strip() or not row["wash_protocol"].strip(): reasons["missing_methods"] += 1
                    if not row["fabric_composition"].strip() or not row["fabric_construction"].strip(): reasons["missing_fabric_metadata"] += 1
                    try:
                        v = float(row["release_value"])
                        import math
                        if not math.isfinite(v) or v < 0: reasons["invalid_mass"] += 1
                    except ValueError:
                        reasons["invalid_mass"] += 1
                    identity = (row["study_id"], row["fabric_id"], row["wash_id"], row["source_locator"])
                    if identity in seen: reasons["duplicate_record"] += 1
                    seen.add(identity)
                    if row["fabric_id"].strip(): distinct_fabrics.add(row["fabric_id"].strip())
                if rows == 0: blockers.append("External CSV has no measurement records")
                if reasons: blockers.append("External CSV has invalid or insufficiently documented records")
        # Even valid CSV fields do not prove the figures were transcribed correctly.
        blockers.append("Manual original-source verification of every external observation is still required")
    return {
        "status": "BLOCKED_EXTERNAL_VALIDATION" if blockers else "MANUAL_REVIEW_REQUIRED",
        "scientific_status": "RESEARCH_ONLY_NOT_DEPLOYABLE",
        "version": "v0.24",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "candidate_study": candidate,
        "comparison_checks": checks,
        "hard_blockers": blockers,
        "warnings": warnings,
        "published_summary_records_not_individual_data": aggregate_count,
        "external_csv_rows": rows,
        "external_csv_unique_fabric_labels": len(distinct_fabrics),
        "external_csv_sha256": sha256,
        "row_issue_counts": dict(sorted(reasons.items())),
        "external_predictions_evaluated": 0,
        "external_metrics_available": False,
        "limitations": [
            "Similar units do not establish protocol compatibility.",
            "Published group means and confidence intervals cannot be treated as independent specimen measurements.",
            "A verified raw dataset and manually approved harmonisation are required before an external test.",
            "Do not use this gate report as an assessment of predictive generalisation."
        ]
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--protocols", default="cross_study_protocols.json")
    p.add_argument("--candidate", default="hazlehurst_2023")
    p.add_argument("--external-csv", default=None)
    p.add_argument("--out", default="data/cross_study_gate_report.json")
    a = p.parse_args()
    path = Path(a.protocols)
    if not path.exists(): p.error("Protocol registry not found: " + str(path))
    protocols = json.loads(path.read_text(encoding="utf-8"))
    csv_path = Path(a.external_csv) if a.external_csv else None
    if csv_path is not None and not csv_path.exists(): p.error("External CSV not found: " + str(csv_path))
    report = gate(protocols, a.candidate, csv_path)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"{report['status']} | candidate={a.candidate} | blockers={len(report['hard_blockers'])} | external tests=0")
    for blocker in report["hard_blockers"]:
        print(" -", blocker)
    print("Saved:", out)
    # Blocked is the EXPECTED truthful scientific result; command itself succeeds.
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
